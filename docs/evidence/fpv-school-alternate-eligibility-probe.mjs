// Manual data qualification for the optional alternate School archives, not unit coverage.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import {
  BEGINNER_LESSONS,
  SELF_LEVEL_LESSON_ORDER,
  EXPERIENCED_LESSON_ORDER,
  ADVANCED_LESSON_ORDER,
} from '../../optional-practice/civilian-fpv/world-catalogue.mjs';
import { worldCourseRequiresAcro } from '../../optional-practice/civilian-fpv/world-model.mjs';
import { importProofPart } from '../../optional-practice/civilian-fpv/world-records.mjs';
import { WORLD_DEMONSTRATIONS } from '../../optional-practice/civilian-fpv/world-demonstrations.mjs';
import { FLIGHT_DEMONSTRATIONS } from '../../optional-practice/civilian-fpv/demonstrations.mjs';

const root = fileURLToPath(new URL('../../', import.meta.url));
const base = 'bf167a4fdfc81d7327fd94518da65ac82d64eb7e';
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex');
const checks = [];
const check = (label, value) => {
  checks.push({ label, passed: Boolean(value) });
  if (!value) throw new Error(label);
};
const expected = new Map([
  ['acro', SELF_LEVEL_LESSON_ORDER],
  ['self-level', [...EXPERIENCED_LESSON_ORDER, ...ADVANCED_LESSON_ORDER]],
]);
const corePairs = new Set(WORLD_DEMONSTRATIONS.map(({ proof }) => `${proof.course}/${proof.mode}`));
check(
  'Core registry remains 154 World plus 24 Flight recordings',
  WORLD_DEMONSTRATIONS.length === 154 && FLIGHT_DEMONSTRATIONS.length === 24,
);
check(
  'All 58 School recommended-mode recordings remain installed',
  BEGINNER_LESSONS.length === 58 &&
    BEGINNER_LESSONS.every(({ id, mode }) => corePairs.has(`${id}/${mode}`)),
);
const eligibility = [];
for (const [mode, ids] of expected) {
  check(`${mode} group has its exact expected count`, ids.length === (mode === 'acro' ? 12 : 16));
  for (const id of ids) {
    const lesson = BEGINNER_LESSONS.find((value) => value.id === id);
    const steps = Object.fromEntries(
      Object.entries(lesson.course.steps).map(([key, value]) => [
        key,
        [...new Set(value.map((step) => step.type))],
      ]),
    );
    check(
      `${id}/${mode} is an absent alternate pair without Acro-only skill steps`,
      lesson.mode !== mode &&
        !corePairs.has(`${id}/${mode}`) &&
        !worldCourseRequiresAcro(lesson.course),
    );
    check(
      `${id} retains equal authored objectives in both modes`,
      JSON.stringify(lesson.course.steps.acro) ===
        JSON.stringify(lesson.course.steps['self-level']),
    );
    eligibility.push({ id, mode, recommendedMode: lesson.mode, stepTypes: steps });
  }
}
const foundation = BEGINNER_LESSONS.filter(({ id }) => /^beginner-(?:1[3-9]|2[0-6])$/.test(id));
const skill = BEGINNER_LESSONS.filter(({ course }) => worldCourseRequiresAcro(course));
check(
  'Existing optional foundation group stays excluded',
  foundation.length === 14 &&
    foundation.every(({ id }) => !eligibility.some((row) => row.id === id)),
);
check(
  'All 16 Acro-skill lessons stay excluded',
  skill.length === 16 && skill.every(({ id }) => !eligibility.some((row) => row.id === id)),
);

const archives = [];
for (const [mode, ids] of expected) {
  const physics = JSON.parse(
    await readFile(new URL(`fpv-school-alternate-${mode}-physics.json`, import.meta.url)),
  );
  check(
    `${mode} generator completed and independently replayed all selected lessons`,
    physics.summary.completed === ids.length &&
      physics.summary.independentlyReplayed === ids.length &&
      physics.summary.archiveRoundTripReplayed === ids.length &&
      physics.results.every((row) => row.contacts === 0 && row.health === 100),
  );
  const imported = [];
  for (const part of physics.archives) {
    const path = `authoring/fpv-worlds/demonstrations/optional/school-alternates-v1/${part.file}`;
    const bytes = await readFile(root + path);
    check(
      `${part.file} matches generated bytes and SHA-256`,
      bytes.length === part.bytes && digest(bytes) === part.fileSha256,
    );
    const records = await importProofPart(bytes.toString());
    check(
      `${part.file} imports without trusting exported verification flags`,
      records.every((row) => row.status === 'missing-dependency'),
    );
    imported.push(...records);
    archives.push({
      path,
      bytes: bytes.length,
      sha256: digest(bytes),
      records: records.length,
      archiveId: part.archiveId,
    });
  }
  check(
    `${mode} imports exactly its expected course-mode pairs`,
    imported.length === ids.length &&
      new Set(imported.map((row) => `${row.course.id}/${row.proof.mode}`)).size === ids.length &&
      ids.every((id) => imported.some((row) => row.course.id === id && row.proof.mode === mode)),
  );
}
execFileSync('git', ['diff', '--exit-code', base, '--', 'game', 'optional-practice'], {
  cwd: root,
});
check('Both tracked production trees remain exact against the baseline', true);
check(
  'No untracked production files extend either tree',
  execFileSync(
    'git',
    ['ls-files', '--others', '--exclude-standard', '--', 'game', 'optional-practice'],
    { cwd: root, encoding: 'utf8' },
  ).trim() === '',
);
const productionTrees = execFileSync('git', ['ls-tree', base, 'game', 'optional-practice'], {
  cwd: root,
  encoding: 'utf8',
})
  .trim()
  .split('\n');
const productionFiles = [
  'scripts/qualify-fpv-acro-school.mjs',
  'optional-practice/civilian-fpv/world-catalogue.mjs',
  'optional-practice/civilian-fpv/world-model.mjs',
  'optional-practice/civilian-fpv/world-records.mjs',
  'optional-practice/civilian-fpv/radio-profile.mjs',
  'optional-practice/civilian-fpv/world-demonstrations.mjs',
  'optional-practice/civilian-fpv/demonstrations.mjs',
  'optional-practice/civilian-fpv/world-app.mjs',
  'optional-practice/civilian-fpv/renderer.mjs',
  'optional-practice/civilian-fpv/world-visuals.mjs',
];
const retained = [];
for (const path of productionFiles) {
  const bytes = await readFile(root + path);
  const original = execFileSync('git', ['show', `${base}:${path}`], {
    cwd: root,
    maxBuffer: 32 * 1024 * 1024,
  });
  check(`${path} stays byte-identical to main qualification baseline`, bytes.equals(original));
  retained.push({ path, bytes: bytes.length, sha256: digest(bytes) });
}
const receipt = {
  format: 'FPVSchoolAlternateEligibility.v1',
  base,
  generatedBy:
    'scripts/qualify-fpv-acro-school.mjs: qualifyAcroSchool explicit mode and proofArchive; no core installation',
  groups: Object.fromEntries(expected),
  eligibility,
  excluded: {
    existingOptionalFoundation: foundation.map(({ id }) => id),
    acroSkillUnscoredSelfLevelOnly: skill.map(({ id }) => id),
  },
  archives,
  totals: {
    optionalRecords: 28,
    bytes: archives.reduce((n, row) => n + row.bytes, 0),
    simulationTicks: 39761,
    coreRecordings: 178,
    newRuntimeSourceBytes: 0,
  },
  retainedProduction: retained,
  productionTrees,
  checks,
  limitations: [
    'Controlled authoring-input reachability does not establish novice usability or physical-radio performance.',
    'Optional archives require explicit import; this evidence does not claim inclusion in the admitted ZIP or a public deployment.',
  ],
};
const output = process.argv[2];
if (!output) throw new Error('Provide a new evidence output path.');
await writeFile(output, JSON.stringify(receipt, null, 2) + '\n', { flag: 'wx' });
console.log(
  JSON.stringify({
    checks: checks.length,
    ...receipt.totals,
    productionFiles: retained.length,
    output,
  }),
);
