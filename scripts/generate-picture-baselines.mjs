import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { canonicalJSON, required } from '../game/data-json.mjs';
import { CURRENT_ART_SOURCES } from '../game/presentation/current-art-sources.mjs';
import { CURRENT_PICTURE_BASELINES } from '../game/presentation/current-picture-baselines.mjs';

export const pictureBaselines = () =>
  CURRENT_ART_SOURCES.filter((row) => row.owner.themeId === 'fpv').map(
    ({ id, kind, fit, image }) => ({ id, kind, fit, image }),
  );
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  required(
    process.argv.length === 3 && ['--check', '--write'].includes(process.argv[2]),
    'Use generate-picture-baselines.mjs --check or --write.',
  );
  const rows = pictureBaselines();
  if (process.argv[2] === '--check') {
    required(
      canonicalJSON(rows) === canonicalJSON(CURRENT_PICTURE_BASELINES),
      'Picture source fingerprints are stale.',
    );
  } else {
    const { format } = await import('prettier');
    const output = await format(
      '// Generated by scripts/generate-picture-baselines.mjs. Exact FPV source fingerprints.\n' +
        '// No original bytes, network paths, board geometry or imported owner locators.\n' +
        `export const CURRENT_PICTURE_BASELINES = ${JSON.stringify(rows, null, 2)};\n`,
      { parser: 'babel', singleQuote: true, printWidth: 100 },
    );
    await fs.writeFile(
      new URL('../game/presentation/current-picture-baselines.mjs', import.meta.url),
      output,
    );
  }
  console.log(
    `${rows.length} exact FPV source fingerprints ${process.argv[2] === '--check' ? 'verified' : 'written'}.`,
  );
}
