/** Exact setup eligibility audit. Qualification routes never manufacture budgets. */
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { dataIdentity } from '../game/data-json.mjs';
import { CLASSIC_SNAKE_LEVELS } from '../game/snake/classic-catalogue.mjs';
import { prepareClassicSnakeLevel } from '../game/snake/classic-setup.mjs';
import { classicSnakeUsesVariableHazards } from '../game/snake/classic-core.mjs';
import {
  classicSnakeRatingForRecord,
  CLASSIC_SNAKE_RATING_REVISION,
} from '../game/snake/classic-ratings.mjs';

const setups = [];
for (const entry of CLASSIC_SNAKE_LEVELS)
  for (const mode of ['solo', 'team'])
    for (const pace of ['normal', 'slow', 'fast']) {
      const level = prepareClassicSnakeLevel(entry, { pace });
      const variableConditions = classicSnakeUsesVariableHazards(level);
      const record = {
        clear: true,
        policy: 'mission',
        mode,
        seed: 17,
        levelIdentity: dataIdentity(level),
        completionOnly: variableConditions,
        fewestMoves: 1,
      };
      const rating = classicSnakeRatingForRecord(record);
      // Neither another level seed nor a different recipe may borrow a budget.
      for (const foreign of [{ seed: 18 }, { levelIdentity: `${record.levelIdentity}-changed` }]) {
        const incompatible = classicSnakeRatingForRecord({ ...record, ...foreign });
        assert.equal(incompatible.calibrated, false);
        assert.equal(incompatible.stars, 1);
      }
      if (variableConditions) assert.equal(rating.calibrated, false);
      setups.push({
        levelId: entry.id,
        mode,
        pace,
        seed: 17,
        levelIdentity: record.levelIdentity,
        variableConditions,
        eligibility: rating.calibrated ? 'existing-fixed-budget' : 'completion-only',
        silverMoves: rating.silverMoves,
        goldMoves: rating.goldMoves,
      });
    }
assert.equal(setups.length, 1440);
const report = {
  format: 'classic-snake-grading-review.v1',
  revision: CLASSIC_SNAKE_RATING_REVISION,
  policy:
    'Verified finite mission clears receive a completion star. Preserve existing exact-setup budgets; new qualification journals do not establish higher grades. Variable schedules remain completion-only. Versus and Endless keep records without mission stars.',
  evidenceLimit:
    'Existing move budgets are retained performance goals, not proven optimal routes or newly player-calibrated difficulty. No higher-star budget is generated by this audit.',
  summary: {
    setups: setups.length,
    existingFixedBudgets: setups.filter((s) => s.eligibility === 'existing-fixed-budget').length,
    completionOnly: setups.filter((s) => s.eligibility === 'completion-only').length,
    variableConditions: setups.filter((s) => s.variableConditions).length,
    incompatibleSeedAndRecipeChecks: setups.length * 2,
  },
  setups,
};
const file = new URL('../docs/verification/snake-remaster/grading-review.json', import.meta.url);
const output = JSON.stringify(report, null, 2) + '\n';
if (process.argv.includes('--check')) assert.equal(await readFile(file, 'utf8'), output);
else await writeFile(file, output);
console.log(JSON.stringify(report.summary));
