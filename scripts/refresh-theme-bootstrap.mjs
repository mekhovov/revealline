import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';
import {
  APPLICATION_THEME_FAMILY,
  BUILTIN_THEME_FAMILIES,
  INSTALLED_THEME_FAMILIES,
  resolvePresentation,
  presentationThemeVariables,
  resolveStoredAppearance,
} from '../game/presentation/theme-system.mjs';

export { createThemeBootstrapSeed } from '../game/presentation/theme-system.mjs';

/** The classic first-paint reader contains only immutable data and the exact
 * shared migration parser. It never loads content or writes a preference. */
export async function buildThemeBootstrap() {
  const seeds = Object.fromEntries(
    INSTALLED_THEME_FAMILIES.map((family) => {
      const current = BUILTIN_THEME_FAMILIES.some(
        (entry) => entry.id === family.id && entry.revision === family.revision,
      );
      const resolved = resolvePresentation({ themeFamily: family });
      const all = presentationThemeVariables(resolved);
      const variables = Object.fromEntries(
        Object.entries(all).filter(
          ([key]) =>
            !key.startsWith('--iw-material-') &&
            !/-(default|hover|pressed|disabled|loading)-/.test(key),
        ),
      );
      const materials = (value) =>
        Object.fromEntries(
          Object.entries(presentationThemeVariables(value)).filter(([key]) =>
            key.startsWith('--iw-material-'),
          ),
        );
      return [
        current ? family.id : `${family.id}@${family.revision}`,
        {
          familyId: family.id,
          variables,
          material: materials(resolved),
          quietMaterial: materials(resolvePresentation({ themeFamily: family, ornaments: 'off' })),
          textured: resolved.textured,
          surface: resolved.surface,
          materialStyle: resolved.materialStyle,
          revision: family.revision,
        },
      ];
    }),
  );
  const contrast = resolvePresentation({
    familyId: APPLICATION_THEME_FAMILY,
    accessibility: { highContrast: true },
  });
  const contrastVariables = Object.fromEntries(
    Object.entries(presentationThemeVariables(contrast)).filter(
      ([key]) =>
        !key.startsWith('--iw-font-') && !/-(default|hover|pressed|disabled|loading)-/.test(key),
    ),
  );
  return format(
    `// Generated by scripts/refresh-theme-bootstrap.mjs. Do not edit the seed data.
// Intentionally a classic script despite the .mjs suffix: runs before first paint.
// It has no preference writer and does not acquire a theme-host lease.
(() => {
  const doc = globalThis.document;
  const root = doc?.documentElement;
  if (!root) return;
  const seeds = ${JSON.stringify(seeds)};
  const contrast = ${JSON.stringify(contrastVariables)};
  let accepted = null;
  try {
    const raw = globalThis.sessionStorage?.getItem('revealline.accepted-appearance-context.v1');
    if(typeof raw === 'string' && raw.length <= 131072) {
      const packet=JSON.parse(raw), now=Date.now();
      if(packet.format === 'AcceptedAppearanceContext.v1' && Number.isSafeInteger(packet.expires) && packet.expires >= now && packet.expires <= now+1800000 && packet.candidate?.family?.id === packet.seed?.familyId && packet.candidate?.family?.revision === packet.seed?.revision) accepted=packet.seed;
    }
  } catch { /* Denied or expired context does not seed this page. */ }
  // Only compiler-emitted or recently accepted, bounded data is accepted here. Variable names,
  // fonts and material syntax cannot introduce arbitrary CSS or resource URLs.
  try {
    for(const raw of [root.dataset.appearanceSeed, accepted && encodeURIComponent(JSON.stringify(accepted))]) {
    if (typeof raw === 'string' && raw.length <= 65536) {
      const seed = JSON.parse(decodeURIComponent(raw));
      const template = seeds[${JSON.stringify(APPLICATION_THEME_FAMILY)}];
      const exact = (value, keys) => value && !Array.isArray(value) && Object.keys(value).length === keys.length && keys.every(key => Object.hasOwn(value, key));
      const colors = /^#[0-9a-f]{6}$/i;
      const validVariable = (key, value) => typeof value === 'string' && value.length < 256 && (colors.test(value) || Object.values(seeds).some(entry => entry.variables[key] === value));
      const material = (values) => exact(values, Object.keys(template.material)) && Object.values(values).every(value => {
        if (typeof value !== 'string' || value.length > 16384 || !value.startsWith('url("data:image/svg+xml,') || !value.endsWith('")')) return false;
        const svg = decodeURIComponent(value.slice(24, -2));
        return ${String.raw`/^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" width="48" height="48" shape-rendering="crispEdges">(?:<path(?: (?:fill="(?:#[a-f0-9]{6}|none)"|stroke="#[a-f0-9]{6}"|opacity="(?:0?\.[0-9]+|1)"|d="[MmLlHhVvQqTtZz0-9 .,-]+")){1,5}\/>)+<\/svg>$/i`}.test(svg);
      });
      if (exact(seed, ['familyId', 'revision', 'variables', 'material', 'quietMaterial', 'textured', 'surface', 'materialStyle']) && /^candidate-[a-z0-9-]{1,54}$/.test(seed.familyId) && seed.revision === 'r1' && !Object.hasOwn(seeds, seed.familyId) && exact(seed.variables, Object.keys(template.variables)) && Object.entries(seed.variables).every(([key, value]) => validVariable(key, value)) && material(seed.material) && material(seed.quietMaterial) && typeof seed.textured === 'boolean' && ['flat', 'bevel'].includes(seed.surface) && Object.values(seeds).some(entry => entry.materialStyle === seed.materialStyle)) seeds[seed.familyId] = seed;
    }
    }
  } catch { /* Damaged compiled hint keeps the app fallback until runtime admission. */ }

  const readAppearance = ${resolveStoredAppearance.toString()};
  const read = (key) => { try { return globalThis.localStorage?.getItem(key) ?? null; } catch { return null; } };
  const legacyDisplay = read('revealline.display.v1');
  const intent = readAppearance({ appearance: read('revealline.appearance.v2'), legacyTheme: read('revealline.theme-family.v1'), legacyMenu: read('revealline.menu-style.v1'), legacyDisplay });
  const hasSeed = (id) => typeof id === 'string' && Object.hasOwn(seeds, id);
  const pinnedSeed = (id, revision) => {
    if (typeof id !== 'string' || typeof revision !== 'string' || id.length > 128 || revision.length > 128) return null;
    if (hasSeed(id) && seeds[id].familyId === id && seeds[id].revision === revision) return id;
    const key = id + '@' + revision;
    return hasSeed(key) && seeds[key].familyId === id && seeds[key].revision === revision ? key : null;
  };
  let seedKey = intent.familyId;
  if (seedKey === 'follow-game') {
    seedKey = ${JSON.stringify(APPLICATION_THEME_FAMILY)};
    // A bounded cosmetic pin can inform a direct launch. It cannot load content.
    try {
      const query = new URL(globalThis.location.href).searchParams;
      const context = query.get('appearanceFamily'), revision = query.get('appearanceRevision');
      const valid = (id, rev) => /^[a-z][a-z0-9-]{0,63}$/.test(id ?? '') && /^r[1-9][0-9]{0,8}$/.test(rev ?? '');
      if (query.getAll('appearanceFamily').length === 1 && query.getAll('appearanceRevision').length === 1 && valid(context, revision)) seedKey = pinnedSeed(context, revision) ?? seedKey;
      else if (valid(root.dataset.appearanceFamily, root.dataset.appearanceRevision)) seedKey = pinnedSeed(root.dataset.appearanceFamily, root.dataset.appearanceRevision) ?? seedKey;
      else if (doc.currentScript?.dataset.themeFollowContext === 'true' && accepted) seedKey = pinnedSeed(accepted.familyId, accepted.revision) ?? seedKey;
    } catch { /* Non-browser test/embedded host. */ }
  }
  if (!hasSeed(seedKey)) seedKey = ${JSON.stringify(APPLICATION_THEME_FAMILY)};
  const seed = seeds[seedKey], id = seed.familyId;
  let display = null;
  try { if (typeof legacyDisplay === 'string' && legacyDisplay.length <= 2048) display = JSON.parse(legacyDisplay); } catch { /* Ignore damaged local data. */ }
  const studio = doc.currentScript?.dataset.themeDensity === 'studio';
  const large = display?.textSize === 'large';
  const plain = display?.textFace === 'plain';
  let coarse = false, reduced = display?.reducedEffects === true;
  try { coarse = globalThis.matchMedia?.('(pointer: coarse)').matches === true; reduced ||= globalThis.matchMedia?.('(prefers-reduced-motion: reduce)').matches === true; } catch { /* Optional media-query API. */ }
  const high = intent.highContrast;
  const textured = seed.textured && intent.ornaments !== 'off' && !high;
  const variables = { ...seed.variables, ...(textured ? seed.material : seed.quietMaterial), ...(high ? contrast : {}) };
  if (plain) variables['--iw-font-display'] = variables['--iw-font-ui'] = "'Field Kit UI', 'Exo 2', sans-serif";
  variables['--iw-target'] = studio && !coarse && !large ? '32px' : '44px';
  variables['--iw-text-size'] = large ? '20px' : '16px';
  for (const [key, value] of Object.entries(variables)) root.style.setProperty(key, value);
  Object.assign(root.dataset, { interfaceTheme: id, themeFamily: id, themeStyled: String(id !== 'legacy' || high), themeContrast: high ? 'high' : 'normal', themeTexture: textured ? 'on' : 'off', themeSurface: high ? 'flat' : seed.surface, themeMaterial: seed.materialStyle, themeHud: high || intent.opaqueHud ? 'opaque' : 'normal', themeMotion: reduced ? 'reduced' : 'full', themeDensity: studio ? 'studio' : 'player', themeTextSize: large ? 'large' : 'standard', themeBootstrapped: 'true' });
  const meta = doc.querySelector?.('meta[name="theme-color"]');
  if (meta && id !== 'legacy') meta.setAttribute('content', variables['--iw-ink']);
})();`,
    { parser: 'babel', singleQuote: true, printWidth: 96 },
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const target = new URL('../game/presentation/theme-bootstrap.mjs', import.meta.url);
  const source = await buildThemeBootstrap();
  if (process.argv.includes('--check')) {
    if ((await fs.readFile(target, 'utf8')) !== source)
      throw new Error(
        'Theme bootstrap seed is stale. Run node scripts/refresh-theme-bootstrap.mjs.',
      );
  } else await fs.writeFile(target, source);
}
