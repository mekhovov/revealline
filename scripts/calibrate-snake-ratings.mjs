import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, relative } from 'node:path';
import { createHash } from 'node:crypto';
import { format as formatCode, resolveConfig } from 'prettier';
import { CLASSIC_SNAKE_LEVELS } from '../game/snake/classic-catalogue.mjs';
import { resolveClassicSnakeRecipeEntry } from '../game/snake/classic-catalogue-archive.mjs';
import { CLASSIC_PACES, prepareClassicSnakeLevel } from '../game/snake/classic-setup.mjs';
import {
  createClassicSnake,
  queueClassicSnakeTurn,
  stepClassicSnake,
  restoreClassicSnakeReplay,
  classicSnakeUsesVariableHazards,
} from '../game/snake/classic-core.mjs';
import { canonicalJSON } from '../game/data-json.mjs';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const evidence = resolve(root, 'docs/verification/classic-snake');
const rows = new Map();
const sources = (await readdir(evidence, { recursive: true }))
  .filter((name) => name.endsWith('.json'))
  .map((name) => resolve(evidence, name));
sources.push(resolve(root, 'game/test/fixtures/classic-snake-v4-proofs.json'));
// Preserve verified grades for the five exact retired fixed-schedule recipes.
// This frozen evidence is reverified on regeneration rather than copying rows.
sources.push(resolve(root, 'game/test/fixtures/classic-snake-v4-archive-proofs.json'));
sources.push(resolve(root, 'game/test/fixtures/classic-snake-field-v3-proofs.json'));
for (const path of sources.sort()) {
  const name = relative(root, path),
    bytes = await readFile(path),
    document = JSON.parse(bytes);
  const proofs =
    document.format === 'classic-snake-v4-proofs.v1'
      ? document.proofs.map((item) => item.replay)
      : [document];
  for (const [proofIndex, proof] of proofs.entries()) {
    if (
      !/^classic-snake-replay\.v[1-4]$/.test(proof.version) ||
      proof.seed !== 17 ||
      !['solo', 'team'].includes(proof.mode)
    )
      continue;
    let entry = CLASSIC_SNAKE_LEVELS.find((candidate) => candidate.id === proof.level.id);
    if (!entry) continue;
    const sourcePace = document.proofs?.[proofIndex]?.pace ?? 'normal';
    try {
      entry = resolveClassicSnakeRecipeEntry(
        entry,
        proof.level,
        {
          pace: sourcePace,
          format: 'campaign',
          targetRules: 'authored',
          preset: 'classic',
        },
        { allowArchive: true },
      );
    } catch {
      continue;
    }
    const expectedLevel = prepareClassicSnakeLevel(entry, {
      pace: sourcePace,
      format: 'campaign',
      targetRules: 'authored',
      preset: 'classic',
    });
    if (canonicalJSON(expectedLevel) !== canonicalJSON(proof.level)) continue;
    const verified = restoreClassicSnakeReplay(proof, { level: expectedLevel });
    if (verified.status !== 'won') continue;
    // A single schedule is completion evidence, never silver/gold calibration
    // for missions whose accepted radio schedule changes on each new attempt.
    if (classicSnakeUsesVariableHazards(expectedLevel)) continue;
    for (const pace of proof.version === 'classic-snake-replay.v4'
      ? [sourcePace]
      : Object.keys(CLASSIC_PACES)) {
      const level = prepareClassicSnakeLevel(entry, {
        pace,
        format: 'campaign',
        targetRules: 'authored',
        preset: 'classic',
      });
      const run = createClassicSnake(level, { mode: proof.mode, seed: 17 });
      let cursor = 0;
      for (let tick = 0; tick <= proof.steps; tick++) {
        while (proof.turns[cursor]?.tick === tick) {
          const turn = proof.turns[cursor++];
          if (!queueClassicSnakeTurn(run, turn.playerId, turn.direction))
            throw new Error(`Calibration turn rejected: ${name}/${pace}`);
        }
        if (tick < proof.steps) stepClassicSnake(run);
      }
      if (run.status !== 'won' || run.tick !== verified.tick)
        throw new Error(`Calibration failed: ${name}/${pace}`);
      const key = `${proof.mode}/mission/${run.levelIdentity}/17`;
      const candidate = {
        key,
        levelId: entry.id,
        mode: proof.mode,
        pace,
        seed: 17,
        levelIdentity: run.levelIdentity,
        goldMoves: Math.ceil(run.tick * 1.25),
        silverMoves: Math.ceil(run.tick * 1.75),
        referenceMoves: run.tick,
        proof: relative(root, path).replaceAll('\\', '/'),
        ...(proofs.length > 1 ? { proofIndex } : {}),
        proofSha256: createHash('sha256').update(bytes).digest('hex'),
      };
      if (!rows.has(key) || rows.get(key).referenceMoves > candidate.referenceMoves)
        rows.set(key, candidate);
    }
  }
}
const text = `// Generated by scripts/calibrate-snake-ratings.mjs from exactly verified winning routes.\n// These generous move budgets are performance goals, not claims of an optimal route.\nexport const CLASSIC_SNAKE_RATING_REVISION = 'authored-seed17.v1';\nexport const CLASSIC_SNAKE_RATING_CALIBRATIONS = Object.freeze(${JSON.stringify(
  [...rows.values()].sort((a, b) => a.key.localeCompare(b.key)),
  null,
  2,
)});\n`;
const output = resolve(root, 'game/snake/classic-rating-calibrations.mjs');
const formatted = await formatCode(text, { ...(await resolveConfig(output)), filepath: output });
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== formatted)
    throw new Error('Snake rating calibration differs. Regenerate its evidence projection.');
} else await writeFile(output, formatted);
console.log(`Verified ${rows.size} exact Snake rating setups.`);
