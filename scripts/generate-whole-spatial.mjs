#!/usr/bin/env node
/** Mechanical snapshot generation only; never enrolls or publishes content. */
import * as fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { required } from '../game/data-json.mjs';
import {
  composeWholeSpatialCandidates,
  WHOLE_SPATIAL_SELECTIONS,
} from './lib/whole-spatial-source.mjs';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
export const WHOLE_SPATIAL_DATA_FILE = 'game/content-design/whole-spatial-data.mjs';

export function renderWholeSpatialSnapshot() {
  const greybox = composeWholeSpatialCandidates();
  const original = composeWholeSpatialCandidates({ artwork: true });
  const field = composeWholeSpatialCandidates({ fieldFinale: true });
  const mission = field.missions.find((item) => item.id === 'home-signal');
  const map = field.maps.find(
    (item) => item.id === mission.map.id && item.revision === mission.map.revision,
  );
  const timed = composeWholeSpatialCandidates({ timedBorder: true });
  const values = {
    WHOLE_SPATIAL_SELECTIONS_JSON: WHOLE_SPATIAL_SELECTIONS,
    WHOLE_SPATIAL_GREYBOX_JSON: greybox,
    WHOLE_SPATIAL_ORIGINAL_JSON: original,
    WHOLE_SPATIAL_FIELD_FINALE_JSON: { mission, map },
    WHOLE_SPATIAL_TIMED_BORDER_JSON: timed.missions.filter((item) =>
      ['behind-the-patrol', 'second-landing', 'long-rail'].includes(item.id),
    ),
  };
  return (
    '// Generated by scripts/generate-whole-spatial.mjs --write. Do not edit.\n' +
    '// Authored source only; shared runtime validation is still required.\n' +
    Object.entries(values)
      .map(
        ([name, value]) =>
          `// prettier-ignore\nexport const ${name} = ${JSON.stringify(JSON.stringify(value))};\n`,
      )
      .join('\n')
  );
}

export async function generateWholeSpatial({ root = ROOT, write = false } = {}) {
  // Fully compose/validate both editions before touching the one generated file.
  const text = renderWholeSpatialSnapshot();
  const destination = path.join(root, WHOLE_SPATIAL_DATA_FILE);
  if (write) await fs.writeFile(destination, text);
  else {
    const current = await fs.readFile(destination, 'utf8');
    required(
      current === text,
      `${WHOLE_SPATIAL_DATA_FILE} is stale. Review any edition changes, then run node scripts/generate-whole-spatial.mjs --write.`,
    );
  }
  return {
    file: WHOLE_SPATIAL_DATA_FILE,
    bytes: Buffer.byteLength(text),
    sha256: createHash('sha256').update(text).digest('hex'),
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  required(
    args.length === 0 || (args.length === 1 && ['--check', '--write'].includes(args[0])),
    'Use --check (default) or --write.',
  );
  console.log(JSON.stringify(await generateWholeSpatial({ write: args.includes('--write') })));
}
