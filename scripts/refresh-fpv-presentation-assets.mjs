import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { EFFECT_BANK } from '../game/audio/effects/bank.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const target = path.join(root, 'optional-practice/civilian-fpv/sim-presentation.mjs');
const rows = [
  ['ui', 'game/ui/fonts/field-kit/exo2-ui-400-600.woff2', 'OFL-1.1'],
  ['pixel', 'game/ui/fonts/departure-mono/DepartureMono-Regular.woff2', 'OFL-1.1'],
  ['focus', 'game/audio/effects/focus.wav', 'CC0-1.0'],
  ['confirm', 'game/audio/effects/confirm.wav', 'CC0-1.0'],
  ['cancel', 'game/audio/effects/cancel.wav', 'CC0-1.0'],
];
const assets = {};
for (const [name, source, license] of rows) {
  const bytes = await readFile(path.join(root, source));
  const sha256 = createHash('sha256').update(bytes).digest('hex');
  if (
    EFFECT_BANK[name] &&
    (EFFECT_BANK[name].bytes !== bytes.length || EFFECT_BANK[name].sha256 !== sha256)
  )
    throw new Error(`Shared ${name} cue differs from its main-game bank identity.`);
  assets[name] = {
    source,
    bytes: bytes.length,
    sha256,
    license,
    base64: bytes.toString('base64'),
  };
}
const start =
  '// BEGIN SHARED SIM ASSETS — generated by scripts/refresh-fpv-presentation-assets.mjs';
const end = '// END SHARED SIM ASSETS';
const source = await readFile(target, 'utf8');
const first = source.indexOf(start);
const last = source.indexOf(end);
if (first < 0 || last < first) throw new Error('Shared asset generation markers are missing.');
const generated = `${start}\n// prettier-ignore\nconst SHARED_ASSETS = ${JSON.stringify(assets, null, 2)};\n${end}`;
const updated = source.slice(0, first) + generated + source.slice(last + end.length);
const check = process.argv.includes('--check');
if (process.argv.slice(2).some((argument) => argument !== '--check'))
  throw new Error('Usage: node scripts/refresh-fpv-presentation-assets.mjs [--check]');
// Formatting outside this generated data block remains owned by the formatter.
if (check && source.slice(first, last + end.length) !== generated)
  throw new Error('Simulator shared assets differ; run the refresh command.');
if (!check) await writeFile(target, updated);
console.log(
  JSON.stringify({
    status: check ? 'verified-byte-identical' : 'refreshed',
    assets: Object.fromEntries(
      Object.entries(assets).map(([name, { base64, ...metadata }]) => [name, metadata]),
    ),
  }),
);
