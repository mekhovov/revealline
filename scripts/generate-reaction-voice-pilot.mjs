import { spawnSync } from 'node:child_process';
import { mkdir, readFile, writeFile, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import { REACTION_LINES } from '../game/journey/reactions.mjs';

const profiles = {
  guide: { en: 'Samantha', uk: 'Lesya', rate: 155 },
  engineer: { en: 'Daniel', uk: 'Lesya', rate: 165 },
  rival: { en: 'Karen', uk: 'Lesya', rate: 175 },
  sentinel: { en: 'Fred', uk: 'Lesya', rate: 145 },
};
function command(executable, args) {
  const result = spawnSync(executable, args, { encoding: 'utf8' });
  if (result.error || result.status !== 0) throw new Error(result.error?.message ?? result.stderr);
  return result.stdout;
}
/** Authoring-only provider. Never shipped as runtime network speech generation. */
export async function macOSSpeechProvider({ text, locale, speaker, output, scratch }) {
  const profile = profiles[speaker],
    voice = profile[locale],
    intermediate = join(scratch, 'speech.aiff');
  command('/usr/bin/say', ['-v', voice, '-r', String(profile.rate), '-o', intermediate, text]);
  command('/usr/bin/afconvert', ['-f', 'm4af', '-d', 'aac', '-b', '64000', intermediate, output]);
  return {
    provider: 'macos-say',
    voice,
    rate: profile.rate,
    kind: 'generated',
    releaseStatus: 'pilot-review-required',
    note: 'Original local speech preview. UK roles share the Lesya voice with different pacing. Listening qualification is pending.',
  };
}
export async function generateReactionVoicePilot({
  outputDirectory,
  synthesize = macOSSpeechProvider,
} = {}) {
  const output =
    outputDirectory ?? fileURLToPath(new URL('../game/audio/reactions/', import.meta.url));
  await mkdir(output, { recursive: true });
  const scratch = await mkdtemp(join(tmpdir(), 'revealline-reactions-'));
  const clips = [];
  try {
    // One result and one in-play capture take per character and language.
    for (const line of REACTION_LINES.filter(
      (entry) => ['result', 'capture'].includes(entry.family) && entry.id.endsWith('/0'),
    ))
      for (const locale of ['en', 'uk']) {
        const file = `${line.speaker}-${line.family === 'capture' ? 'capture-' : ''}${line.id.split('/').at(-1)}-${locale}.m4a`,
          path = join(output, file);
        const provenance = await synthesize({
          text: line.text[locale],
          locale,
          speaker: line.speaker,
          output: path,
          scratch,
        });
        const bytes = await readFile(path);
        clips.push({
          lineId: line.id,
          locale,
          transcript: line.text[locale],
          file,
          bytes: bytes.length,
          sha256: createHash('sha256').update(bytes).digest('hex'),
          mime: 'audio/mp4',
          provenance,
        });
      }
    await writeFile(
      join(output, 'pilot.mjs'),
      `// Generated by scripts/generate-reaction-voice-pilot.mjs. Original transcripts are the source of truth.\nexport const REACTION_VOICE_PILOT = Object.freeze(${JSON.stringify(clips, null, 2)});\n`,
    );
    return { clips: clips.length, bytes: clips.reduce((sum, clip) => sum + clip.bytes, 0), output };
  } finally {
    await rm(scratch, { recursive: true, force: true });
  }
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href)
  console.log(JSON.stringify(await generateReactionVoicePilot(), null, 2));
