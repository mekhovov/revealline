/** Pin Sound Studio's published destruction slots into existing optional-package
 * projections. Older releases use the registered core recordings. */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import { validateCompiledPresentation } from '../game/presentation/host.mjs';
import { EFFECT_BANK } from '../game/audio/effects/bank.mjs';
import { HUMAN_REACTION_BANK } from '../game/audio/human-reactions/portable.mjs';
import { DESTRUCTION_CUES, HUMAN_REACTION_CUES } from '../game/ui/destruction-audio.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
const target = 'game/audio/portable-destruction.mjs';
export const PORTABLE_DESTRUCTION_MAX_BYTES = 1024 * 1024;

export async function buildPortableDestructionAudio({ compiled, readAsset, readDefault } = {}) {
  const release = validateCompiledPresentation(compiled);
  const clips = {};
  let total = 0;
  for (const name of [...DESTRUCTION_CUES, ...HUMAN_REACTION_CUES]) {
    const slot = `audio.${name}`,
      asset = release.resolved.assets[slot];
    let bytes, mime, sha256, source;
    if (asset?.kind === 'audio') {
      ({ mime, sha256 } = asset.file);
      const file = release.urls[sha256];
      if (!/^\.\/assets\/[a-f0-9]{64}\.(wav|ogg|mp3)$/.test(file))
        throw new Error(`Invalid published recording path: ${slot}`);
      if (asset.file.bytes > PORTABLE_DESTRUCTION_MAX_BYTES)
        throw new Error(`Portable destruction recording exceeds package budget: ${slot}`);
      bytes = Buffer.from(await readAsset(file));
      if (bytes.length !== asset.file.bytes || hash(bytes) !== sha256)
        throw new Error(`Published destruction recording differs from its release: ${slot}`);
      source = { kind: 'published', id: asset.id, revision: asset.revision };
    } else if (HUMAN_REACTION_BANK[name]) {
      const compact = HUMAN_REACTION_BANK[name];
      bytes = Buffer.from(compact.base64, 'base64');
      mime = compact.mime;
      sha256 = hash(bytes);
      source = { kind: 'core-compact', recordingSha256: EFFECT_BANK[name].sha256 };
    } else {
      const original = EFFECT_BANK[name];
      bytes = Buffer.from(await readDefault(original.file));
      if (bytes.length !== original.bytes || hash(bytes) !== original.sha256)
        throw new Error(`Core destruction recording differs from its bank: ${slot}`);
      mime = 'audio/wav';
      sha256 = original.sha256;
      source = { kind: 'core', recordingSha256: sha256 };
    }
    total += bytes.length;
    if (total > PORTABLE_DESTRUCTION_MAX_BYTES)
      throw new Error('Portable destruction recordings exceed their aggregate package budget.');
    clips[slot] = { mime, bytes: bytes.length, sha256, source, base64: bytes.toString('base64') };
  }
  return {
    format: 'revealline-portable-destruction.v1',
    release: release.source,
    bytes: total,
    clips,
  };
}

export async function refreshPortableDestructionAudio({ directory = root, check = false } = {}) {
  const bank = await buildPortableDestructionAudio({
    compiled: JSON.parse(
      await fs.readFile(path.join(directory, 'game/presentation/compiled/runtime.json'), 'utf8'),
    ),
    readAsset: (file) => fs.readFile(path.join(directory, 'game/presentation/compiled', file)),
    readDefault: (file) => fs.readFile(path.join(directory, 'game/audio/effects', file)),
  });
  const generated = `// Generated by scripts/refresh-portable-destruction-audio.mjs. Original bytes and provenance retained.\n// prettier-ignore\nconst bank = ${JSON.stringify(bank)};\nfor (const clip of Object.values(bank.clips)) {\n  Object.freeze(clip.source);\n  Object.freeze(clip);\n}\nObject.freeze(bank.release);\nObject.freeze(bank.clips);\nexport const PORTABLE_DESTRUCTION_AUDIO = Object.freeze(bank);\n`;
  const file = path.join(directory, target);
  if (check) {
    if ((await fs.readFile(file, 'utf8')) !== generated)
      throw new Error(
        'Portable destruction recordings are stale; refresh them before the FPV projections.',
      );
  } else {
    const temporary = `${file}.${process.pid}.tmp`;
    try {
      await fs.writeFile(temporary, generated, { flag: 'wx' });
      await fs.rename(temporary, file);
    } finally {
      await fs.rm(temporary, { force: true });
    }
  }
  return {
    release: bank.release,
    recordings: Object.keys(bank.clips).length,
    originalBytes: bank.bytes,
    moduleBytes: Buffer.byteLength(generated),
  };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  if (process.argv.slice(2).some((arg) => arg !== '--check')) throw new Error('Use [--check].');
  console.log(
    JSON.stringify(
      await refreshPortableDestructionAudio({ check: process.argv.includes('--check') }),
    ),
  );
}
