import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { editionAppIdentity } from '../game/edition-context.mjs';

export const LAUNCHER_FILE_LIMIT = 128 * 1024;
export const LAUNCHER_CATALOG_KEYS = Object.freeze({
  common: Object.freeze(['language.label', 'language.sessionOnly']),
  interface: Object.freeze([
    'launcher.opening',
    'launcher.play',
    'launcher.install',
    'launcher.checkUpdates',
    'launcher.restorePrevious',
    'launcher.prepare',
    'launcher.installHelp',
    'launcher.appleHelp',
    'launcher.checkFailed',
    'launcher.editionSelected',
    'launcher.editionAvailable',
    'launcher.checkError',
    'launcher.installedEdition',
    'launcher.chooseEdition',
    'launcher.preparationFailed',
  ]),
});

async function buildLauncherCatalog(root) {
  const resources = {};
  for (const language of ['en', 'uk']) {
    resources[language] = {};
    for (const [namespace, keys] of Object.entries(LAUNCHER_CATALOG_KEYS)) {
      const source = JSON.parse(
        await fs.readFile(path.join(root, 'game/locales', language, namespace + '.json'), 'utf8'),
      );
      const selected = {};
      for (const key of keys) {
        if (!Object.hasOwn(source, key))
          throw new Error(
            'Launcher translation is missing: ' + language + '/' + namespace + ':' + key,
          );
        selected[key] = source[key];
      }
      resources[language][namespace] = selected;
    }
  }
  return Buffer.from(
    '// Generated by scripts/offline-launcher.mjs from the canonical locale sources.\n' +
      'globalThis.RevealLineTranslations = ' +
      JSON.stringify(resources) +
      ';\n',
  );
}

export async function addOfflineLauncher(root, entries, version, options = {}) {
  if (!entries.some((entry) => entry.name === 'game/installed-app.mjs')) return;
  const launcher = [];
  const add = (name, bytes) => {
    if (bytes.length > LAUNCHER_FILE_LIMIT)
      throw new Error('Frozen launcher exceeded its file budget: ' + name);
    launcher.push({ name: 'app/' + name, bytes });
  };
  for (const [target, source] of [
    ['index.html', 'game/offline/app.html'],
    ['app.mjs', 'game/offline/app.mjs'],
    ['app.css', 'game/downloads.css'],
    ['installed-app.mjs', 'game/installed-app.mjs'],
    ['edition-context.mjs', 'game/edition-context.mjs'],
    ['profile-writer.mjs', 'game/profile-writer.mjs'],
    ['i18n/index.mjs', 'game/i18n/index.mjs'],
    ['i18n/bootstrap.mjs', 'game/i18n/bootstrap.mjs'],
    ['i18n/style.css', 'game/i18n/style.css'],
    ['vendor/i18next-26.4.2.min.js', 'game/vendor/i18next-26.4.2.min.js'],
  ])
    add(target, await fs.readFile(path.join(root, source)));
  add('i18n/catalogs.mjs', await buildLauncherCatalog(root));
  for (const size of [180, 192, 512])
    add(
      'icon-' + size + '.png',
      entries.find((entry) => entry.name === 'icons/icon-' + size + '.png').bytes,
    );
  add(
    'manifest.webmanifest',
    Buffer.from(
      JSON.stringify({
        id: './',
        name: 'Reveal Line',
        short_name: 'Reveal Line',
        start_url: './',
        scope: '../',
        display: 'fullscreen',
        display_override: ['fullscreen', 'standalone'],
        orientation: 'any',
        background_color: '#091324',
        theme_color: '#091324',
        lang: 'en',
        ...(options.editionId === undefined
          ? {}
          : {
              ...editionAppIdentity(options),
              name: options.name || options.editionId,
              short_name: options.name || options.editionId,
            }),
        icons: [192, 512].map((size) => ({
          src: 'icon-' + size + '.png',
          sizes: size + 'x' + size,
          type: 'image/png',
          purpose: 'any maskable',
        })),
      }),
    ),
  );
  const template = await fs.readFile(
    path.join(root, 'game/offline/app-worker.template.js'),
    'utf8',
  );
  const id = createHash('sha256')
    .update(template)
    .update(Buffer.concat(launcher.map((entry) => entry.bytes)))
    .digest('hex');
  add(
    'service-worker.js',
    Buffer.from(
      template.replace(
        '__REVEALLINE_LAUNCHER_CONFIG__',
        JSON.stringify({
          id,
          files: launcher.map((entry) => ({
            path: entry.name.slice(4),
            bytes: entry.bytes.length,
            sha256: createHash('sha256').update(entry.bytes).digest('hex'),
          })),
        }),
      ),
    ),
  );
  add(
    'current.json',
    Buffer.from(
      JSON.stringify({
        version,
        scope: '../',
        ...(options.editionId === undefined ? {} : { editionId: options.editionId }),
      }),
    ),
  );
  entries.push(...launcher);
}
