#!/usr/bin/env node
/** Reproducible public-input demonstrations for the ordinary authored catalog. */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { survivalDemoInventory } from '../game/demo-modes/survival-catalog.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const directory = resolve(root, 'game/demo-data/survival');
const identityPath = resolve(root, 'game/demo-modes/survival-simulation-identity.mjs');
const check = process.argv.includes('--check');
const selected = process.argv.find((arg) => arg.startsWith('--level='))?.slice(8);
const paths = new Map();
async function collect(path) {
  if (paths.has(path)) return;
  const body = await readFile(path, 'utf8');
  paths.set(path, body);
  for (const match of body.matchAll(/(?:from\s*|import\s*)['"]([^'"]+)['"]/g)) {
    if (!match[1].startsWith('.')) continue;
    const child = resolve(dirname(path), match[1]);
    // Localized validation messages do not participate in native simulation.
    if (child.startsWith(resolve(root, 'game/i18n') + '/')) continue;
    if (child.endsWith('.mjs')) await collect(child);
  }
}
await collect(resolve(root, 'game/overflight/core.mjs'));
await collect(resolve(root, 'game/overflight/project.mjs'));
const bindings = [...paths]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([path, body]) => ({
    path: relative(root, path),
    sha256: createHash('sha256').update(body).digest('hex'),
  }));
const simulationIdentity = createHash('sha256').update(JSON.stringify(bindings)).digest('hex');
const generatedIdentity = `// Generated by scripts/generate-survival-demos.mjs; binds native simulation dependencies.\nexport const SURVIVAL_DEMO_SIMULATION_IDENTITY =\n  '${simulationIdentity}';\n`;
if (check) {
  if ((await readFile(identityPath, 'utf8')) !== generatedIdentity)
    throw new Error(
      'Survival simulation changed: regenerate and independently verify demonstrations.',
    );
} else {
  await mkdir(directory, { recursive: true });
  await writeFile(identityPath, generatedIdentity);
}
const { verifySurvivalDemo } = await import('../game/demo-modes/survival-replay.mjs');
const { authorSurvivalDemo } = await import('../game/demo-modes/survival-authoring.mjs');
const inventory = survivalDemoInventory();
const report = [];
for (const entry of inventory.filter((item) => !selected || item.levelId === selected)) {
  const file = resolve(directory, `${entry.levelId}.replay.json`);
  const started = performance.now();
  let proof;
  if (check) proof = JSON.parse(await readFile(file, 'utf8'));
  else {
    proof = await authorSurvivalDemo(entry, { yieldEvery: Infinity });
  }
  // A second, separately constructed native world consumes only the transcript.
  const summary = await verifySurvivalDemo(entry, proof, { yieldEvery: Infinity });
  if (!check) await writeFile(file, `${JSON.stringify(proof)}\n`);
  const item = {
    levelId: entry.levelId,
    variantId: entry.variantId,
    outcome: summary.outcome,
    ticks: summary.tick,
    seconds: summary.time,
    kills: summary.stats.kills,
    salvage: summary.stats.xpCollected,
    upgrades: summary.stats.upgradesChosen,
    rerolls: summary.stats.rerollsUsed,
    checkpoints: proof.checkpoints.length,
  };
  report.push(item);
  console.log(
    `${check ? 'Verified' : 'Generated and verified'} ${entry.levelId}: ${summary.outcome}, ${summary.time}s, ${summary.stats.upgradesChosen} upgrades (${Math.round(performance.now() - started)}ms)`,
  );
}
if (!selected && !check)
  await writeFile(
    resolve(directory, 'catalog.json'),
    `${JSON.stringify(
      {
        format: 'SurvivalDemoCatalogV1',
        simulationIdentity,
        bindings,
        entries: report,
      },
      null,
      2,
    )}\n`,
  );
console.log(
  `${report.length}/${selected ? 1 : inventory.length} required Survival demonstrations qualified.`,
);
