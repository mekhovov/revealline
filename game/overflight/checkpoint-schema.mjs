// The checkpoint language is deliberately smaller than JavaScript objects.
// Every persisted edge has a declared type. Adding a runtime field requires an
// explicit schema revision/decision, rather than teaching an importer new tags.
const words = (source) => source.trim().split(/\s+/).filter(Boolean);
const fields = (names, type = 'number') =>
  Object.fromEntries(words(names).map((key) => [key, type]));
const record = (required, optional = {}) => ({ kind: 'record', required, optional });
const list = (of, max) => ({ kind: 'list', of, max });
const map = (key, of, max) => ({ kind: 'map', key, of, max });
const typed = (constructor, max) => ({ kind: 'typed', constructor, max });

